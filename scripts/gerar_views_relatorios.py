f.write('        seis_meses = hoje - timedelta(days=180)\n')
f.write('        vendas_por_mes = (Venda.objects.filter(status="confirmada", data_venda__gte=seis_meses)\n')
f.write('            .annotate(mes=TruncMonth("data_venda")).values("mes")\n')
